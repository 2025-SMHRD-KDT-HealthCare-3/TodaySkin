# ──────────────────────────────────────────────
# * 데일리 코멘트 서비스 (report_comment.py)
# - 오늘 피부 종합 점수와 이전 대비 변화량 기반 한줄 코멘트 생성
# - 텍스트 응답 (JSON 아님)
# ──────────────────────────────────────────────


import logging

from langchain_openai import ChatOpenAI
from langchain_core.prompts import ChatPromptTemplate


logger = logging.getLogger(__name__)


# ========== LLM 설정 ==========
# 한줄 코멘트라 토큰 적게 필요
_llm = ChatOpenAI(model="gpt-4o-mini", max_tokens=200)




# ========== 프롬프트 템플릿 ==========
_prompt = ChatPromptTemplate.from_template(
    """당신은 감각적인 피부 관리 어드바이저입니다.
사용자의 여드름과 모공 점수를 보고, 오늘의 피부 상태를 한눈에 느낄 수 있는 임팩트 있는 한줄 진단을 작성합니다.

[점수 기준]
- 85점 이상: 매우 좋음 → 칭찬하되 유지 강조
- 70~84점: 양호 → 잘 하고 있지만 개선 여지 있음을 언급
- 50~69점: 관리 필요 → 구체적인 주의 사항 강조
- 50점 미만: 집중 관리 → 강한 주의와 격려 동시에

[주의]
- 점수가 70~84점이면 절대 "완벽", "훌륭", "최상" 같은 표현을 쓰지 마세요.
- 점수가 낮을수록 더 구체적이고 경각심을 줄 수 있는 표현을 사용하세요.
- 여드름과 모공 중 낮은 점수 쪽을 반드시 언급하세요.

[분석 정보]
- 피부 타입: {skin_type}
- 여드름 점수: {acne_score}점
- 모공 점수: {pore_score}점

[작성 규칙]
1. 반드시 딱 1문장으로만 작성하세요.
2. 점수 수치(숫자)는 절대 포함하지 마세요.
3. 여드름과 모공 중 더 심각한 쪽을 중심으로 작성하세요.
4. 문장은 "오늘 피부는~", "지금 피부가~" 같은 현재 상태 중심으로 시작하세요.
5. 사용자가 읽었을 때 "맞아, 그렇구나" 하고 공감할 수 있도록 구체적이고 생생하게 표현하세요.
6. 너무 딱딱하거나 의학적인 표현은 피하고, 친근하지만 전문적인 톤을 유지하세요.
7. 문장 끝에 상황에 어울리는 이모지 1개를 붙이세요.
8. 다른 설명 텍스트는 절대 포함하지 마세요.

[좋은 예시]
- 오늘 피부는 모공이 눈에 띄게 넓어진 날, 저녁 딥클렌징이 꼭 필요해요 🧖
- 여드름이 한창 예민한 상태라 자극을 최소화한 순한 케어가 필요한 날이에요 🌿
- 피부 컨디션이 꽤 좋은 편이니 오늘은 보습에만 집중해도 충분해요 ✨
""")

# ========== 체인 구성 ==========
_chain = _prompt | _llm

# ========== 데일리 코멘트 생성 ==========

def generate_daily_comment(req):
    """
    오늘의 여드름/모공 점수 기반 한줄 진단 생성
    """
    # 이전 데이터 비교 로직을 삭제하고 현재 점수만 전달
    result = _chain.invoke({
        "skin_type": req.skin_type or "정보 없음",
        "acne_score": req.acne_score,
        "pore_score": req.pore_score,
    })

    return {
        "status": "success",
        "data": {
            "line_comment": result.content.strip()
        }
    }